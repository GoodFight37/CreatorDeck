-- --------------------------------------------------------------------------
-- Table des créateurs
-- --------------------------------------------------------------------------
create table if not exists public.creators (
  slug         text primary key,
  login        text,
  display_name text not null,
  rarity       text not null check (rarity in ('common','uncommon','rare','epic','legendary')),
  rank         integer not null,
  region       text
);

-- Colonnes ajoutées après coup : les bases existantes les reçoivent ici.
alter table public.creators add column if not exists login text;
alter table public.creators add column if not exists region text;
create index if not exists creators_region_idx on public.creators (region);

-- RLS : lecture seule pour les joueurs connectés, aucune écriture cliente.
alter table public.creators enable row level security;

drop policy if exists "lecture du catalogue" on public.creators;
create policy "lecture du catalogue"
  on public.creators for select
  to authenticated
  using (true);

