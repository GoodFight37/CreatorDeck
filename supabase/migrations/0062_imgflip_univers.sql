  v_next timestamptz;
  -- Instantané des tables Live ; vérifié contre pull-rates.json par le test local.
  v_rates constant jsonb := '{"slots":[{"weights":{"common":42,"uncommon":30,"rare":18,"epic":8,"legendary":2}},{"weights":{"common":42,"uncommon":30,"rare":18,"epic":8,"legendary":2}},{"weights":{"common":34,"uncommon":32,"rare":22,"epic":10,"legendary":2}},{"weights":{"common":20,"uncommon":34,"rare":28,"epic":15,"legendary":3}}],"guaranteed":{"weights":{"rare":82,"epic":15,"legendary":3}},"rareDrop":{"label":"Perfect Live","tagline":"Les 5 cartes en Épique ou mieux.","chancePermille":1,"weights":{"epic":82,"legendary":18},"variantUpgradePermille":900},"pity":12}'::jsonb;
  v_perfect boolean;
  v_weights jsonb;
  v_candidate text;
  v_weight integer;
begin
  if v_user is null then
    raise exception 'Connecte-toi pour ouvrir les boosters Imgflip.' using errcode = 'P0001';
  end if;
  if p_request_id is null then
    raise exception 'Réessaie pour préparer le booster Imgflip.' using errcode = 'P0001';
  end if;
  v_row := public._imgflip_refill(v_user);
  select * into v_old from public.imgflip_openings
    where user_id = v_user and request_id = p_request_id;
  if found then
    return jsonb_build_object('cards', v_old.cards, 'stock', v_old.stock_after,
      'next_at', v_old.next_at, 'replayed', true);
  end if;
  if v_row.stock < 1 then
    raise exception 'Aucun booster Imgflip disponible pour le moment.' using errcode = 'P0001';
  end if;
  v_perfect := public._pack_random_int(1000) < (v_rates #>> '{rareDrop,chancePermille}')::integer;
  for v_slot in 1..5 loop
    if v_slot = 5 and v_row.dry_streak >= (v_rates ->> 'pity')::integer then
      v_weights := '{"legendary":1}'::jsonb;
    elsif v_perfect then
      v_weights := v_rates #> '{rareDrop,weights}';
    elsif v_slot = 5 then
      v_weights := v_rates #> '{guaranteed,weights}';
    else
      v_weights := v_rates -> 'slots' -> (v_slot - 1) -> 'weights';
    end if;
    select sum(value::integer)::integer into v_weight from jsonb_each_text(v_weights);
    v_roll := public._pack_random_int(v_weight);
    foreach v_candidate in array array['common','uncommon','rare','epic','legendary'] loop
      v_roll := v_roll - coalesce((v_weights ->> v_candidate)::integer, 0);
      if v_roll < 0 then
        v_rarity := v_candidate;
        exit;
      end if;
    end loop;
    select id into v_card from public.imgflip_catalog
      where rarity = v_rarity and pullable and not (id = any(v_cards))
      order by random() limit 1;
    if v_card is null then
      raise exception 'Catalogue Imgflip incomplet : réessaie plus tard.' using errcode = 'P0001';
    end if;
    v_cards := array_append(v_cards, v_card);
    insert into public.imgflip_collection(user_id, card_id, copies)
      values (v_user, v_card, 1)
      on conflict (user_id, card_id) do update
        set copies = public.imgflip_collection.copies + 1, last_at = now();
  end loop;
  update public.imgflip_profile
    set stock = v_row.stock - 1,
        anchor_at = case when v_row.stock = 4 then now() else v_row.anchor_at end,
        openings = v_row.openings + 1,
        dry_streak = case when exists (
          select 1 from public.imgflip_catalog where id = any(v_cards) and rarity = 'legendary'
        ) then 0 else v_row.dry_streak + 1 end,
        updated_at = now()
    where user_id = v_user returning * into v_row;
  v_next := case when v_row.stock < 4 then v_row.anchor_at + interval '30 minutes' else null end;
  insert into public.imgflip_openings(user_id, request_id, cards, stock_after, next_at)
    values (v_user, p_request_id, v_cards, v_row.stock, v_next);
  return jsonb_build_object('cards', v_cards, 'stock', v_row.stock, 'next_at', v_next,
    'replayed', false);
end;
$$;
