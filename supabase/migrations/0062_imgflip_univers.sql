create or replace function public._imgflip_refill(p_user uuid)
returns public.imgflip_profile
language plpgsql security definer set search_path = ''
as $$
declare
  v_row public.imgflip_profile;
  v_steps integer;
  v_stock integer;
  v_now timestamptz := now();
begin
  insert into public.imgflip_profile(user_id) values (p_user) on conflict do nothing;
  select * into v_row from public.imgflip_profile where user_id = p_user for update;
  if v_row.stock < 4 then
    v_steps := greatest(0, floor(extract(epoch from (v_now - v_row.anchor_at)) / 1800)::integer);
    if v_steps > 0 then
      v_stock := least(4, v_row.stock + v_steps);
      update public.imgflip_profile
        set stock = v_stock,
            anchor_at = case when v_stock = 4 then v_now
                             else v_row.anchor_at + v_steps * interval '30 minutes' end,
            updated_at = v_now
        where user_id = p_user returning * into v_row;
    end if;
  end if;
  return v_row;
end;
$$;
revoke all on function public._imgflip_refill(uuid) from public, anon, authenticated;

create or replace function public.imgflip_status()
returns jsonb
language plpgsql security definer set search_path = ''
as $$
declare
  v_user uuid := auth.uid();
  v_row public.imgflip_profile;
  v_owned jsonb;
begin
  if v_user is null then
    raise exception 'Connecte-toi pour ouvrir les boosters Imgflip.' using errcode = 'P0001';
  end if;
  v_row := public._imgflip_refill(v_user);
  select coalesce(jsonb_agg(jsonb_build_object('id', card_id, 'copies', copies)
    order by card_id), '[]'::jsonb)
    into v_owned from public.imgflip_collection where user_id = v_user;
  return jsonb_build_object(
    'stock', v_row.stock,
    'next_at', case when v_row.stock < 4 then v_row.anchor_at + interval '30 minutes' else null end,
    'openings', v_row.openings,
    'owned', v_owned
  );
end;
$$;
revoke all on function public.imgflip_status() from public, anon;
grant execute on function public.imgflip_status() to authenticated;

