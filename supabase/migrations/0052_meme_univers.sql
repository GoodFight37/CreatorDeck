create table if not exists public.meme_catalog (
  id text primary key,
  title text not null,
  rarity text not null check (rarity in ('common','rare','epic','legendary','mythic')),
  full_art boolean not null default false,
  pullable boolean not null default true
);

create table if not exists public.meme_profile (
  user_id uuid primary key references auth.users(id) on delete cascade,
  stock integer not null default 4 check (stock between 0 and 4),
  anchor_at timestamptz not null default now(),
  openings integer not null default 0 check (openings >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists public.meme_collection (
  user_id uuid not null references auth.users(id) on delete cascade,
  card_id text not null references public.meme_catalog(id),
  copies integer not null default 1 check (copies > 0),
  first_at timestamptz not null default now(),
  last_at timestamptz not null default now(),
  primary key (user_id, card_id)
);

create table if not exists public.meme_openings (
  user_id uuid not null references auth.users(id) on delete cascade,
  request_id uuid not null,
  cards text[] not null check (array_length(cards, 1) = 5),
  stock_after integer not null check (stock_after between 0 and 4),
  next_at timestamptz,
  created_at timestamptz not null default now(),
  primary key (user_id, request_id)
);

