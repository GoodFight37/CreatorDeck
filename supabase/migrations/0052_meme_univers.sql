create or replace function public._meme_refill(p_user uuid)
returns public.meme_profile
language plpgsql security definer set search_path = ''
as $$
declare
  v_row public.meme_profile;
  v_steps integer;
  v_stock integer;
  v_now timestamptz := now();
begin
  insert into public.meme_profile(user_id) values (p_user) on conflict do nothing;
  select * into v_row from public.meme_profile where user_id = p_user for update;
  if v_row.stock < 4 then
    v_steps := greatest(0, floor(extract(epoch from (v_now - v_row.anchor_at)) / 1800)::integer);
    if v_steps > 0 then
      v_stock := least(4, v_row.stock + v_steps);
      update public.meme_profile
        set stock = v_stock,
            anchor_at = case when v_stock = 4 then v_now
                             else v_row.anchor_at + v_steps * interval '30 minutes' end,
            updated_at = v_now
        where user_id = p_user returning * into v_row;
    end if;
  end if;
  return v_row;
end;
$$;
revoke all on function public._meme_refill(uuid) from public, anon, authenticated;

create or replace function public.meme_status()
returns jsonb
language plpgsql security definer set search_path = ''
as $$
declare
  v_user uuid := auth.uid();
  v_row public.meme_profile;
  v_owned jsonb;
begin
  if v_user is null then
    raise exception 'Connecte-toi pour ouvrir les boosters Mèmes.' using errcode = 'P0001';
  end if;
  v_row := public._meme_refill(v_user);
  select coalesce(jsonb_agg(jsonb_build_object('id', card_id, 'copies', copies)
    order by card_id), '[]'::jsonb)
    into v_owned from public.meme_collection where user_id = v_user;
  return jsonb_build_object(
    'stock', v_row.stock,
    'next_at', case when v_row.stock < 4 then v_row.anchor_at + interval '30 minutes' else null end,
    'openings', v_row.openings,
    'owned', v_owned
  );
end;
$$;
revoke all on function public.meme_status() from public, anon;
grant execute on function public.meme_status() to authenticated;

create or replace function public.open_meme_pack(p_request_id uuid)
returns jsonb
language plpgsql security definer set search_path = ''
as $$
declare
  v_user uuid := auth.uid();
  v_row public.meme_profile;
  v_old public.meme_openings;
  v_cards text[] := '{}';
  v_slot integer;
  v_roll double precision;
  v_rarity text;
  v_card text;
  v_next timestamptz;
begin
  if v_user is null then
    raise exception 'Connecte-toi pour ouvrir les boosters Mèmes.' using errcode = 'P0001';
  end if;
  if p_request_id is null then
    raise exception 'Réessaie pour préparer le booster Mèmes.' using errcode = 'P0001';
  end if;
  v_row := public._meme_refill(v_user);
  select * into v_old from public.meme_openings
    where user_id = v_user and request_id = p_request_id;
  if found then
    return jsonb_build_object('cards', v_old.cards, 'stock', v_old.stock_after,
      'next_at', v_old.next_at, 'replayed', true);
  end if;
  if v_row.stock < 1 then
    raise exception 'Aucun booster Mèmes disponible pour le moment.' using errcode = 'P0001';
  end if;
  for v_slot in 1..5 loop
    v_roll := random();
    if v_slot <= 3 then
      v_rarity := 'common';
    elsif v_slot = 4 then
      v_rarity := case when v_roll < .55 then 'common'
                       when v_roll < .90 then 'rare'
                       when v_roll < .98 then 'epic'
                       when v_roll < .998 then 'legendary'
                       else 'mythic' end;
    else
      v_rarity := case when v_roll < .82 then 'rare'
                       when v_roll < .97 then 'epic'
                       when v_roll < .995 then 'legendary'
                       else 'mythic' end;
    end if;
    select id into v_card from public.meme_catalog
      where rarity = v_rarity and pullable and not (id = any(v_cards))
      order by random() limit 1;
    if v_card is null then
      raise exception 'Catalogue Mèmes incomplet : réessaie plus tard.' using errcode = 'P0001';
    end if;
    v_cards := array_append(v_cards, v_card);
    insert into public.meme_collection(user_id, card_id, copies)
      values (v_user, v_card, 1)
      on conflict (user_id, card_id) do update
        set copies = public.meme_collection.copies + 1, last_at = now();
  end loop;
  update public.meme_profile
    set stock = v_row.stock - 1,
        anchor_at = case when v_row.stock = 4 then now() else v_row.anchor_at end,
        openings = v_row.openings + 1, updated_at = now()
    where user_id = v_user returning * into v_row;
  v_next := case when v_row.stock < 4 then v_row.anchor_at + interval '30 minutes' else null end;
  insert into public.meme_openings(user_id, request_id, cards, stock_after, next_at)
    values (v_user, p_request_id, v_cards, v_row.stock, v_next);
  return jsonb_build_object('cards', v_cards, 'stock', v_row.stock, 'next_at', v_next,
    'replayed', false);
end;
$$;
revoke all on function public.open_meme_pack(uuid) from public, anon;
grant execute on function public.open_meme_pack(uuid) to authenticated;
