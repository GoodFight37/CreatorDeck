-- CreatorDeck — les familles et leurs paliers, vus par le serveur.
--
-- **Fichier généré** par `scripts/build-supabase-seasons.mjs` depuis
-- `src/data/creators.json` et `src/data/seasons.config.json`, avec le module
-- partagé `scripts/lib/seasons-split.mjs` — celui-là même que l'écran utilise
-- (`src/lib/seasons.ts`). Ne pas modifier à la main : relancer le script.
--
-- À coller **après** `0027_wallet.sql` (qui lit ces deux tables) : c'est ce
-- qui permet au serveur de vérifier un palier de famille au lieu de croire le
-- client sur parole.
--
-- 12 saisons, 1000 créateurs, 4 points par créateur.
-- Rejouable : la table est vidée puis remplie, donc un catalogue régénéré
-- remplace l'ancienne grille au lieu de s'y ajouter.

-- --------------------------------------------------------------------------
-- 1. Les créateurs de chaque vague
-- --------------------------------------------------------------------------
-- Une saison (`S04-2`) est un morceau de famille ; ses créateurs sont ceux que
-- le serveur compte pour savoir si un palier est atteint. La clé primaire porte
-- les deux colonnes : un créateur ne peut pas être deux fois dans une vague, et
-- une vague ne peut pas se contredire d'un collage à l'autre.
create table if not exists public.wallet_season_members (
  season_id    text not null,
  creator_slug text not null,
  primary key (season_id, creator_slug)
);

create index if not exists wallet_season_members_slug_idx on public.wallet_season_members (creator_slug);

-- --------------------------------------------------------------------------
-- 2. Les paliers de chaque vague
-- --------------------------------------------------------------------------
-- `tier` est le rang du palier dans la vague (1 à 4) : le client réclame
-- `S04-2#3`, le serveur relit ici le seuil (`required`) et les points (`points`).
-- Le journal des mouvements (`wallet_ledger`) garantit qu'un palier ne se paie
-- qu'une fois, sans qu'aucune colonne n'ait à le dire ici.
create table if not exists public.wallet_season_tiers (
  season_id text not null,
  tier      integer not null check (tier >= 1),
  required  integer not null check (required >= 1),
  points    integer not null check (points >= 0),
  primary key (season_id, tier)
);

-- Fermées au client, comme le reste du wallet : le joueur passe par les
-- fonctions, jamais par les tables.
alter table public.wallet_season_members enable row level security;
alter table public.wallet_season_tiers enable row level security;
revoke all on table public.wallet_season_members from public, anon, authenticated;
revoke all on table public.wallet_season_tiers from public, anon, authenticated;

